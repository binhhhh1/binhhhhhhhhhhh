import React, { useCallback, useEffect, useRef, useState } from 'react';
import {
  createUserWithEmailAndPassword,
  onAuthStateChanged,
  sendEmailVerification,
  signInWithEmailAndPassword,
  signOut,
  updateProfile,
} from 'firebase/auth';
import { AuthModal, type AuthModalSubmitPayload } from './components/auth/AuthModal';
import { ErrorBoundary } from './components/ErrorBoundary';
import { NotificationDrawer } from './components/layout/NotificationDrawer';
import { Sidebar } from './components/layout/Sidebar';
import { TopHeader } from './components/layout/TopHeader';
import { AvailabilityView } from './components/views/AvailabilityView';
import { DailyTrainingView, type DailyTrainingTab } from './components/views/DailyTrainingView';
import { DashboardView } from './components/views/DashboardView';
import { PerformanceView } from './components/views/PerformanceView';
import { ScrimScheduleView } from './components/views/ScrimScheduleView';
import { TeamManagementView } from './components/views/TeamManagementView';
import {
  buildDemoDataset,
  loadDemoState,
  resetDemoState,
  saveDemoState,
  type HubDataset,
} from './data/demoSeed';
import { auth, testConnection } from './services/firebase';
import {
  getActiveLocalSession,
  listLocalAccountIdentifiers,
  loginLocalAccount,
  logoutLocalAccount,
  registerLocalAccount,
  saveAccountWorkspace,
  type LocalAccountRecord,
} from './services/localAuth';
import {
  createClientId,
  deleteAimLogFromFirestore,
  deleteAvailabilityFromFirestore,
  deleteDrillFromFirestore,
  deleteScrimFromFirestore,
  deleteTeamMemberFromFirestore,
  ensureUserAndTeamWorkspace,
  saveAimLogToFirestore,
  saveAvailabilityToFirestore,
  saveDrillToFirestore,
  saveNotificationToFirestore,
  saveScrimToFirestore,
  saveTeamMemberToFirestore,
  saveTemplateToFirestore,
  subscribeTeamWorkspaceData,
  verifyAimProofInFirestore,
  verifyDrillProofInFirestore,
} from './services/firestoreSync';
import type {
  AiDailyPlan,
  AimLog,
  AvailabilitySlot,
  DataSourceMode,
  NavSection,
  Scrim,
  TeamMember,
  TeamNotification,
  TeamRole,
  TeamWorkspace,
  TrainingDrill,
  TrainingTemplate,
  UserProfile,
} from './types/training';
import {
  buildDailyAiCacheKey,
  DEFAULT_AI_FOCUS_AREAS,
  shouldAutoGenerateDailyPlan,
} from './utils/aiDrills';
import {
  getLocalProofImage,
  removeLocalProofImage,
  saveLocalProofImage,
} from './utils/aimProof';
import { computeAimAnalytics } from './utils/analytics';
import { getVNDateKey, getVNTimeStr } from './utils/timezone';

function AppShell() {
  const [activeSection, setActiveSection] = useState<NavSection>('dashboard');
  const [dailyTab, setDailyTab] = useState<DailyTrainingTab>('drills');
  const [mobileMenuOpen, setMobileMenuOpen] = useState(false);
  const [notificationsOpen, setNotificationsOpen] = useState(false);

  const handleNavigate = (section: NavSection, subTab?: DailyTrainingTab) => {
    setActiveSection(section);
    if (section === 'daily-training' && subTab) {
      setDailyTab(subTab);
    }
  };

  const [initialLocal] = useState(() => getActiveLocalSession());
  const [dataMode, setDataMode] = useState<DataSourceMode>(
    initialLocal ? 'local_account' : 'demo',
  );
  const [demoData, setDemoData] = useState<HubDataset>(() => loadDemoState());
  const [localAccount, setLocalAccount] = useState<LocalAccountRecord | null>(
    initialLocal?.session.account ?? null,
  );
  const [localProfile, setLocalProfile] = useState<UserProfile | null>(
    initialLocal?.session.profile ?? null,
  );
  const [localAccountData, setLocalAccountData] = useState<HubDataset | null>(
    initialLocal?.dataset ?? null,
  );
  const [demoRolePreview, setDemoRolePreview] = useState<TeamRole>('coach');

  // Auth modal & Cloud state
  const [authModalOpen, setAuthModalOpen] = useState(false);
  const [authReady, setAuthReady] = useState(false);
  const [authBusy, setAuthBusy] = useState(false);
  const [authError, setAuthError] = useState('');
  const [verifyNotice, setVerifyNotice] = useState('');
  const [cloudProfile, setCloudProfile] = useState<UserProfile | null>(null);
  const [cloudTeam, setCloudTeam] = useState<TeamWorkspace | null>(null);
  const [cloudMembers, setCloudMembers] = useState<TeamMember[]>([]);
  const [cloudDrills, setCloudDrills] = useState<TrainingDrill[]>([]);
  const [cloudAimLogs, setCloudAimLogs] = useState<AimLog[]>([]);
  const [cloudScrims, setCloudScrims] = useState<Scrim[]>([]);
  const [cloudAvailabilities, setCloudAvailabilities] = useState<AvailabilitySlot[]>([]);
  const [cloudTemplates, setCloudTemplates] = useState<TrainingTemplate[]>([]);
  const [cloudNotifications, setCloudNotifications] = useState<TeamNotification[]>([]);
  const [cloudLoading, setCloudLoading] = useState(false);

  // Daily AI Drills state
  const [aiPlan, setAiPlan] = useState<AiDailyPlan | null>(null);
  const [aiLoading, setAiLoading] = useState(false);
  const [aiError, setAiError] = useState('');
  const autoAiAttemptedKeysRef = useRef<Set<string>>(new Set());

  // Startup Firestore connectivity check
  useEffect(() => {
    void testConnection();
  }, []);

  // Firebase Auth & Firestore Subscription
  useEffect(() => {
    let unsubData: (() => void) | null = null;

    const unsubAuth = onAuthStateChanged(auth, async (user) => {
      if (unsubData) {
        unsubData();
        unsubData = null;
      }

      if (!user) {
        setCloudProfile(null);
        setCloudTeam(null);
        setVerifyNotice('');
        setDataMode(getActiveLocalSession() ? 'local_account' : 'demo');
        setAuthReady(true);
        setCloudLoading(false);
        return;
      }

      if (!user.emailVerified) {
        setVerifyNotice(
          `Email ${user.email} chưa được xác minh. Vui lòng kiểm tra hộp thư để xác minh trước khi đồng bộ Cloud Firestore (hoặc đăng xuất để dùng tài khoản cục bộ).`,
        );
        setAuthReady(true);
        setCloudLoading(false);
        return;
      }

      setVerifyNotice('');
      setCloudLoading(true);
      setAuthError('');
      try {
        const { profile, team } = await ensureUserAndTeamWorkspace(user);
        setCloudProfile(profile);
        setCloudTeam(team);
        setDataMode('cloud');
        setAuthReady(true);

        unsubData = subscribeTeamWorkspaceData({
          teamId: team.id,
          teamOwnerId: team.ownerId,
          onMembers: setCloudMembers,
          onDrills: setCloudDrills,
          onAimLogs: setCloudAimLogs,
          onScrims: setCloudScrims,
          onAvailabilities: setCloudAvailabilities,
          onTemplates: setCloudTemplates,
          onNotifications: setCloudNotifications,
        });
      } catch (err) {
        setAuthError(
          err instanceof Error
            ? err.message
            : 'Không thể khởi tạo dữ liệu Cloud Firestore.',
        );
      } finally {
        setCloudLoading(false);
      }
    });

    return () => {
      unsubAuth();
      if (unsubData) unsubData();
    };
  }, []);

  // Persist Demo or Local Account changes locally
  const updateDemo = (updater: (prev: HubDataset) => HubDataset) => {
    if (dataMode === 'local_account' && localAccount) {
      setLocalAccountData((prev) => {
        const base = prev ?? buildDemoDataset();
        const next = updater(base);
        saveAccountWorkspace(localAccount.uid, next);
        return next;
      });
      return;
    }
    setDemoData((prev) => {
      const next = updater(prev);
      saveDemoState(next);
      return next;
    });
  };

  // Active resolved state
  const isCloud = dataMode === 'cloud' && cloudTeam !== null && cloudProfile !== null;
  const isLocalAccount =
    dataMode === 'local_account' && localAccount !== null && localAccountData !== null;
  const userProfile = isCloud ? cloudProfile : isLocalAccount ? localProfile : null;

  const team = isCloud
    ? cloudTeam
    : isLocalAccount
    ? localAccountData.team
    : demoData.team;
  const members = isCloud
    ? cloudMembers
    : isLocalAccount
    ? localAccountData.members
    : demoData.members;
  const rawDrills = isCloud
    ? cloudDrills
    : isLocalAccount
    ? localAccountData.drills
    : demoData.drills;
  const drills = isCloud
    ? rawDrills.map((d) => {
        const cachedImg = getLocalProofImage(`drill_${d.id}`);
        return cachedImg && !d.proofImageDataUrl
          ? { ...d, proofImageDataUrl: cachedImg }
          : d;
      })
    : rawDrills;
  const rawAimLogs = isCloud
    ? cloudAimLogs
    : isLocalAccount
    ? localAccountData.aimLogs
    : demoData.aimLogs;
  const aimLogs = isCloud
    ? rawAimLogs.map((l) => {
        const cachedImg = getLocalProofImage(l.id);
        return cachedImg && !l.proofImageDataUrl
          ? { ...l, proofImageDataUrl: cachedImg }
          : l;
      })
    : rawAimLogs;
  const scrims = isCloud
    ? cloudScrims
    : isLocalAccount
    ? localAccountData.scrims
    : demoData.scrims;
  const availabilities = isCloud
    ? cloudAvailabilities
    : isLocalAccount
    ? localAccountData.availabilities
    : demoData.availabilities;
  const templates = isCloud
    ? cloudTemplates
    : isLocalAccount
    ? localAccountData.templates
    : demoData.templates;
  const notifications = isCloud
    ? cloudNotifications
    : isLocalAccount
    ? localAccountData.notifications
    : demoData.notifications;

  const currentUserId = isCloud
    ? cloudProfile.uid
    : isLocalAccount
    ? localAccount.uid
    : demoRolePreview === 'coach'
    ? demoData.team.ownerId
    : 'demo_player_kyro';

  const currentMemberName = isCloud
    ? cloudProfile.displayName
    : isLocalAccount
    ? localAccount.displayName
    : demoRolePreview === 'coach'
    ? 'Coach Vũ Lâm'
    : 'Hoàng "Kyro" Minh';

  const activeRole: TeamRole = isCloud
    ? members.find((m) => m.uid === cloudProfile.uid)?.teamRole ||
      (cloudTeam.ownerId === cloudProfile.uid ? 'coach' : 'player')
    : isLocalAccount
    ? localAccount.teamRole
    : demoRolePreview;

  // Daily AI Plan Generation (auto once per VN date + manual refresh)
  const todayDateKey = getVNDateKey();
  const activeAccountKey = isCloud
    ? cloudProfile.uid
    : isLocalAccount
    ? localAccount.uid
    : 'demo';

  const generateDailyAiPlan = useCallback(
    async (options?: {
      focusAreas?: string[];
      durationBudgetMin?: number;
      force?: boolean;
    }) => {
      const cacheKey = buildDailyAiCacheKey(activeAccountKey, todayDateKey);
      if (!options?.force) {
        try {
          const cachedRaw = localStorage.getItem(cacheKey);
          if (cachedRaw) {
            const cached = JSON.parse(cachedRaw) as AiDailyPlan;
            if (!shouldAutoGenerateDailyPlan(cached?.date, todayDateKey) && cached.drills?.length > 0) {
              setAiPlan(cached);
              setAiError('');
              return;
            }
          }
        } catch {
          // ignore malformed cache
        }
      }

      setAiLoading(true);
      setAiError('');
      try {
        const aimStats = computeAimAnalytics(aimLogs, todayDateKey);
        const currentMember = members.find((m) => m.uid === currentUserId);
        const res = await fetch('/api/ai/generate-daily-drills', {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({
            date: todayDateKey,
            playerName: currentMemberName,
            gameRole: userProfile?.gameRole || currentMember?.gameRole || 'Duelist',
            mainAgent: userProfile?.mainAgent || currentMember?.mainAgent || 'Jett',
            focusAreas:
              options?.focusAreas && options.focusAreas.length > 0
                ? options.focusAreas
                : [...DEFAULT_AI_FOCUS_AREAS.slice(0, 4)],
            durationBudgetMin: options?.durationBudgetMin ?? 90,
            recentStats: {
              avgAccuracy: aimStats.weekOverWeek.thisWeekAvgAccuracy,
              lastScore:
                aimStats.dailyScoreSeries[aimStats.dailyScoreSeries.length - 1]?.value ??
                aimStats.highScore ??
                0,
              totalSessions: aimLogs.length,
            },
          }),
        });

        const data = (await res.json()) as AiDailyPlan & { error?: string };
        if (!res.ok) {
          throw new Error(
            data?.error || `Máy chủ trả về lỗi HTTP ${res.status} khi tạo bài tập AI.`,
          );
        }
        setAiPlan(data);
        try {
          localStorage.setItem(cacheKey, JSON.stringify(data));
        } catch {
          // ignore storage quota
        }
      } catch (err) {
        setAiError(
          err instanceof Error
            ? err.message
            : 'Không thể tạo giáo án bài tập AI lúc này.',
        );
      } finally {
        setAiLoading(false);
      }
    },
    [
      activeAccountKey,
      aimLogs,
      currentMemberName,
      currentUserId,
      members,
      todayDateKey,
      userProfile?.gameRole,
      userProfile?.mainAgent,
    ],
  );

  useEffect(() => {
    const cacheKey = buildDailyAiCacheKey(activeAccountKey, todayDateKey);
    try {
      const cachedRaw = localStorage.getItem(cacheKey);
      if (cachedRaw) {
        const cached = JSON.parse(cachedRaw) as AiDailyPlan;
        if (!shouldAutoGenerateDailyPlan(cached?.date, todayDateKey) && cached.drills?.length > 0) {
          setAiPlan(cached);
          setAiError('');
          return;
        }
      }
    } catch {
      // ignore invalid cache
    }

    setAiPlan(null);
    if (autoAiAttemptedKeysRef.current.has(cacheKey)) {
      return;
    }
    autoAiAttemptedKeysRef.current.add(cacheKey);
    void generateDailyAiPlan();
  }, [activeAccountKey, todayDateKey, generateDailyAiPlan]);

  // Auth Actions
  const handleOpenAuthModal = () => {
    setAuthError('');
    setAuthModalOpen(true);
  };

  const handleAuthSubmit = async (payload: AuthModalSubmitPayload) => {
    setAuthBusy(true);
    setAuthError('');
    try {
      if (payload.useCloudSync) {
        if (!payload.identifier.includes('@')) {
          throw new Error(
            'Đồng bộ Cloud Firebase yêu cầu nhập địa chỉ Email hợp lệ. Hoặc bỏ chọn đồng bộ Cloud để dùng tên đăng nhập riêng.',
          );
        }
        if (payload.mode === 'register') {
          const cred = await createUserWithEmailAndPassword(
            auth,
            payload.identifier.trim(),
            payload.password,
          );
          if (payload.displayName?.trim()) {
            await updateProfile(cred.user, {
              displayName: payload.displayName.trim(),
            });
          }
          await sendEmailVerification(cred.user);
          setAuthModalOpen(false);
          setVerifyNotice(
            `Đã tạo tài khoản Cloud (${cred.user.email}) và gửi email xác minh. Hãy mở email bấm xác nhận rồi tải lại trang để bật Cloud Firestore.`,
          );
        } else {
          const cred = await signInWithEmailAndPassword(
            auth,
            payload.identifier.trim(),
            payload.password,
          );
          setAuthModalOpen(false);
          if (!cred.user.emailVerified) {
            await sendEmailVerification(cred.user);
            setVerifyNotice(
              `Email ${cred.user.email} chưa xác minh. Đã gửi lại link xác minh tới hộp thư của bạn.`,
            );
          }
        }
        return;
      }

      if (payload.mode === 'register') {
        const { session, dataset } = await registerLocalAccount({
          identifier: payload.identifier,
          password: payload.password,
          displayName: payload.displayName || '',
          riotId: payload.riotId || '',
          teamRole: payload.teamRole || 'player',
          gameRole: payload.gameRole || 'Duelist',
          mainAgent: payload.mainAgent || 'Jett',
        });
        setLocalAccount(session.account);
        setLocalProfile(session.profile);
        setLocalAccountData(dataset);
        setDataMode('local_account');
        setAuthModalOpen(false);
      } else {
        const { session, dataset } = await loginLocalAccount(
          payload.identifier,
          payload.password,
        );
        setLocalAccount(session.account);
        setLocalProfile(session.profile);
        setLocalAccountData(dataset);
        setDataMode('local_account');
        setAuthModalOpen(false);
      }
    } catch (err) {
      const code = (err as { code?: string })?.code;
      if (code === 'auth/operation-not-allowed') {
        setAuthError(
          'Firebase Console chưa bật phương thức Email/Password. Hãy bật Email/Password trong Firebase Authentication Console hoặc bỏ tích "Đồng bộ Cloud" để tạo ngay tài khoản riêng.',
        );
      } else {
        setAuthError(
          err instanceof Error ? err.message : 'Không thể xác thực tài khoản.',
        );
      }
    } finally {
      setAuthBusy(false);
    }
  };

  const handleSignOut = async () => {
    if (isCloud || auth.currentUser) {
      await signOut(auth);
    }
    logoutLocalAccount();
    setLocalAccount(null);
    setLocalProfile(null);
    setLocalAccountData(null);
    setVerifyNotice('');
    setDataMode('demo');
  };

  // Helper to emit a notification
  const pushNotification = async (
    type: TeamNotification['type'],
    title: string,
    message: string,
  ) => {
    const notif: TeamNotification = {
      id: createClientId('notif'),
      teamId: team.id,
      teamOwnerId: team.ownerId,
      actorId: currentUserId,
      type,
      title,
      message,
      read: false,
      isDemo: !isCloud,
      createdAt: `${getVNDateKey()}T${getVNTimeStr()}:00+07:00`,
    };
    if (isCloud) {
      await saveNotificationToFirestore(notif, true);
    } else {
      updateDemo((prev) => ({
        ...prev,
        notifications: [notif, ...prev.notifications],
      }));
    }
  };

  // --- Handlers wired to both Demo LocalStorage & Cloud Firestore ---
  const handleSaveDrill = async (drill: TrainingDrill, isNew: boolean) => {
    if (isCloud) {
      saveLocalProofImage(`drill_${drill.id}`, drill.proofImageDataUrl || '');
      await saveDrillToFirestore(drill, isNew);
    } else {
      updateDemo((prev) => ({
        ...prev,
        drills: isNew
          ? [{ ...drill, isDemo: false }, ...prev.drills]
          : prev.drills.map((d) => (d.id === drill.id ? { ...drill, isDemo: false } : d)),
      }));
    }
  };

  const handleVerifyDrillProof = async (drillId: string, verified: boolean) => {
    if (isCloud) {
      await verifyDrillProofInFirestore(team.id, drillId, verified);
    } else {
      updateDemo((prev) => ({
        ...prev,
        drills: prev.drills.map((d) =>
          d.id === drillId ? { ...d, proofVerified: verified } : d,
        ),
      }));
    }
  };

  const handleDeleteDrill = async (drillId: string) => {
    removeLocalProofImage(`drill_${drillId}`);
    if (isCloud) {
      await deleteDrillFromFirestore(team.id, drillId);
    } else {
      updateDemo((prev) => ({
        ...prev,
        drills: prev.drills.filter((d) => d.id !== drillId),
      }));
    }
  };

  const handleDuplicateDrill = async (drill: TrainingDrill) => {
    const copy: TrainingDrill = {
      ...drill,
      id: createClientId('drill'),
      title: `${drill.title} (Bản sao)`,
      status: 'todo',
      actualResult: '',
      notes: '',
    };
    await handleSaveDrill(copy, true);
  };

  const handleApplyTemplate = async (tpl: TrainingTemplate, targetDate: string) => {
    for (let i = 0; i < tpl.items.length; i++) {
      const item = tpl.items[i];
      const newDrill: TrainingDrill = {
        id: createClientId(`drill_${i}`),
        teamId: team.id,
        teamOwnerId: team.ownerId,
        ownerId: currentUserId,
        assignedBy: currentUserId,
        title: item.title,
        category: item.category,
        date: targetDate,
        startTime: item.startTime,
        durationMin: item.durationMin,
        goal: item.goal || '',
        description: item.description || '',
        status: 'todo',
      };
      await handleSaveDrill(newDrill, true);
    }
  };

  const handleSaveTemplate = async (tpl: TrainingTemplate) => {
    if (isCloud) {
      await saveTemplateToFirestore(tpl, true);
    } else {
      updateDemo((prev) => ({
        ...prev,
        templates: [tpl, ...prev.templates],
      }));
    }
  };

  const handleSaveAimLog = async (log: AimLog, isNew: boolean) => {
    if (isCloud) {
      saveLocalProofImage(log.id, log.proofImageDataUrl || '');
      await saveAimLogToFirestore(log, isNew);
    } else {
      updateDemo((prev) => ({
        ...prev,
        aimLogs: isNew
          ? [{ ...log, isDemo: false }, ...prev.aimLogs]
          : prev.aimLogs.map((l) => (l.id === log.id ? { ...log, isDemo: false } : l)),
      }));
    }
  };

  const handleVerifyAimProof = async (logId: string, verified: boolean) => {
    if (isCloud) {
      await verifyAimProofInFirestore(team.id, logId, verified);
    } else {
      updateDemo((prev) => ({
        ...prev,
        aimLogs: prev.aimLogs.map((l) =>
          l.id === logId ? { ...l, proofVerified: verified } : l,
        ),
      }));
    }
  };

  const handleDeleteAimLog = async (logId: string) => {
    removeLocalProofImage(logId);
    if (isCloud) {
      await deleteAimLogFromFirestore(team.id, logId);
    } else {
      updateDemo((prev) => ({
        ...prev,
        aimLogs: prev.aimLogs.filter((l) => l.id !== logId),
      }));
    }
  };

  const handleSaveScrim = async (scrim: Scrim, isNew: boolean) => {
    if (isCloud) {
      await saveScrimToFirestore(scrim, isNew);
    } else {
      updateDemo((prev) => ({
        ...prev,
        scrims: isNew
          ? [{ ...scrim, isDemo: false }, ...prev.scrims]
          : prev.scrims.map((s) => (s.id === scrim.id ? scrim : s)),
      }));
    }
    await pushNotification(
      isNew ? 'scrim_created' : 'scrim_updated',
      isNew ? 'Lịch Scrim mới' : 'Lịch Scrim đã cập nhật',
      `vs ${scrim.opponent} · ${scrim.date} ${scrim.startTime}–${scrim.endTime} (${scrim.status}).`,
    );
  };

  const handleDeleteScrim = async (scrimId: string) => {
    if (isCloud) {
      await deleteScrimFromFirestore(team.id, scrimId);
    } else {
      updateDemo((prev) => ({
        ...prev,
        scrims: prev.scrims.filter((s) => s.id !== scrimId),
      }));
    }
  };

  const handleSaveAvailability = async (slot: AvailabilitySlot, isNew: boolean) => {
    if (isCloud) {
      await saveAvailabilityToFirestore(slot, isNew);
    } else {
      updateDemo((prev) => ({
        ...prev,
        availabilities: isNew
          ? [{ ...slot, isDemo: false }, ...prev.availabilities]
          : prev.availabilities.map((a) => (a.id === slot.id ? slot : a)),
      }));
    }
    await pushNotification(
      'availability_updated',
      'Cập nhật lịch trống',
      `${slot.memberName} đã đăng ký ${slot.slotType === 'available' ? 'rảnh' : 'bận'} (${slot.date} ${slot.startTime}–${slot.endTime}).`,
    );
  };

  const handleDeleteAvailability = async (slotId: string) => {
    if (isCloud) {
      await deleteAvailabilityFromFirestore(team.id, slotId);
    } else {
      updateDemo((prev) => ({
        ...prev,
        availabilities: prev.availabilities.filter((a) => a.id !== slotId),
      }));
    }
  };

  const handleSaveMember = async (member: TeamMember, isNew: boolean) => {
    if (isCloud) {
      await saveTeamMemberToFirestore(team.id, member, isNew);
    } else {
      updateDemo((prev) => ({
        ...prev,
        members: isNew
          ? [...prev.members, member]
          : prev.members.map((m) => (m.uid === member.uid ? member : m)),
      }));
    }
  };

  const handleDeleteMember = async (memberUid: string) => {
    if (memberUid === team.ownerId || memberUid === currentUserId) {
      return;
    }
    if (isCloud) {
      await deleteTeamMemberFromFirestore(team.id, memberUid);
    } else {
      updateDemo((prev) => ({
        ...prev,
        members: prev.members.filter((m) => m.uid !== memberUid),
        availabilities: prev.availabilities.filter((a) => a.ownerId !== memberUid),
      }));
    }
  };

  const handleAssignDrill = async (drill: TrainingDrill) => {
    await handleSaveDrill(drill, true);
    const targetName =
      members.find((m) => m.uid === drill.ownerId)?.displayName || 'Thành viên';
    await pushNotification(
      'drill_assigned',
      'Bài tập mới được giao',
      `Coach đã giao "${drill.title}" (${drill.durationMin}m) cho ${targetName}.`,
    );
  };

  const handleMarkNotifRead = async (id: string) => {
    const target = notifications.find((n) => n.id === id);
    if (!target) return;
    if (isCloud) {
      await saveNotificationToFirestore({ ...target, read: true }, false);
    } else {
      updateDemo((prev) => ({
        ...prev,
        notifications: prev.notifications.map((n) =>
          n.id === id ? { ...n, read: true } : n,
        ),
      }));
    }
  };

  const handleMarkAllNotifsRead = async () => {
    const unread = notifications.filter((n) => !n.read);
    if (isCloud) {
      await Promise.all(
        unread.map((n) => saveNotificationToFirestore({ ...n, read: true }, false)),
      );
    } else {
      updateDemo((prev) => ({
        ...prev,
        notifications: prev.notifications.map((n) => ({ ...n, read: true })),
      }));
    }
  };

  const handleResetDemo = () => {
    setDemoData(resetDemoState());
  };

  const handleClearDemo = () => {
    const base = buildDemoDataset();
    const empty: HubDataset = {
      team: { ...base.team, name: 'My Training Hub', tag: 'VTH', isDemo: false },
      members: [
        {
          uid: currentUserId,
          teamOwnerId: base.team.ownerId,
          displayName: currentMemberName,
          riotId: 'Player#VN1',
          teamRole: 'coach',
          gameRole: 'Flex',
          mainAgent: 'Omen',
          scrimStatus: 'ready',
        },
      ],
      drills: [],
      aimLogs: [],
      scrims: [],
      availabilities: [],
      templates: base.templates,
      notifications: [],
    };
    saveDemoState(empty);
    setDemoData(empty);
  };

  const unreadCount = notifications.filter((n) => !n.read).length;

  return (
    <div className="min-h-screen bg-[#090B10] text-slate-100 flex">
      <Sidebar
        activeSection={activeSection}
        onSelectSection={setActiveSection}
        team={team}
        dataMode={dataMode}
        activeRole={activeRole}
        mobileOpen={mobileMenuOpen}
        onCloseMobile={() => setMobileMenuOpen(false)}
      />

      <div className="flex-1 min-w-0 flex flex-col">
        <TopHeader
          activeSection={activeSection}
          unreadNotifications={unreadCount}
          onOpenNotifications={() => setNotificationsOpen(true)}
          onOpenMobileMenu={() => setMobileMenuOpen(true)}
          dataMode={dataMode}
          userProfile={userProfile}
          activeRole={activeRole}
          isAdminAccount={Boolean(isLocalAccount && localAccount?.isAdmin)}
          onSignIn={handleOpenAuthModal}
          onSignOut={handleSignOut}
          authBusy={authBusy}
        />

        <main className="flex-1 p-4 lg:p-6 max-w-[1440px] w-full mx-auto space-y-5">
          {verifyNotice && (
            <div className="p-3.5 rounded-xl bg-amber-500/15 border border-amber-400/40 text-xs text-amber-100 flex items-center justify-between gap-3">
              <span>{verifyNotice}</span>
              <button
                type="button"
                onClick={() => setVerifyNotice('')}
                className="text-white underline shrink-0"
              >
                Đóng
              </button>
            </div>
          )}

          {authError && !authModalOpen && (
            <div className="p-3.5 rounded-xl bg-[#FF4655]/15 border border-[#FF4655]/40 text-xs text-red-200 flex items-center justify-between gap-3">
              <span>{authError}</span>
              <button
                type="button"
                onClick={() => setAuthError('')}
                className="text-white underline shrink-0"
              >
                Đóng
              </button>
            </div>
          )}

          {cloudLoading && !authReady ? (
            <div className="grid grid-cols-1 md:grid-cols-4 gap-4">
              {[1, 2, 3, 4].map((i) => (
                <div
                  key={i}
                  className="h-24 rounded-xl bg-[#121621] border border-white/[0.06] animate-pulse"
                />
              ))}
            </div>
          ) : (
            <>
              {activeSection === 'dashboard' && (
                <DashboardView
                  team={team}
                  dataMode={dataMode}
                  drills={drills}
                  aimLogs={aimLogs}
                  scrims={scrims}
                  availabilities={availabilities}
                  activeOwnerId={activeRole === 'player' ? currentUserId : undefined}
                  aiPlan={aiPlan}
                  aiLoading={aiLoading}
                  onOpenAuthModal={handleOpenAuthModal}
                  onNavigate={handleNavigate}
                  onToggleDrillComplete={(drill) =>
                    handleSaveDrill(
                      {
                        ...drill,
                        status: drill.status === 'completed' ? 'todo' : 'completed',
                      },
                      false,
                    )
                  }
                  onResetDemo={handleResetDemo}
                  onClearDemo={handleClearDemo}
                />
              )}

              {activeSection === 'daily-training' && (
                <DailyTrainingView
                  drills={drills}
                  templates={templates}
                  members={members}
                  aimLogs={aimLogs}
                  activeRole={activeRole}
                  currentUserId={currentUserId}
                  dataMode={dataMode}
                  teamId={team.id}
                  teamOwnerId={team.ownerId}
                  activeTab={dailyTab}
                  onTabChange={setDailyTab}
                  aiPlan={aiPlan}
                  aiLoading={aiLoading}
                  aiError={aiError}
                  onGenerateAiPlan={generateDailyAiPlan}
                  onSaveDrill={handleSaveDrill}
                  onVerifyDrillProof={handleVerifyDrillProof}
                  onDeleteDrill={handleDeleteDrill}
                  onDuplicateDrill={handleDuplicateDrill}
                  onApplyTemplate={handleApplyTemplate}
                  onSaveTemplate={handleSaveTemplate}
                  onSaveAimLog={handleSaveAimLog}
                  onVerifyAimProof={handleVerifyAimProof}
                  onDeleteAimLog={handleDeleteAimLog}
                />
              )}

              {activeSection === 'scrim-schedule' && (
                <ScrimScheduleView
                  scrims={scrims}
                  drills={drills}
                  availabilities={availabilities}
                  activeRole={activeRole}
                  currentUserId={currentUserId}
                  teamId={team.id}
                  teamOwnerId={team.ownerId}
                  onSaveScrim={handleSaveScrim}
                  onDeleteScrim={handleDeleteScrim}
                />
              )}

              {activeSection === 'availability' && (
                <AvailabilityView
                  availabilities={availabilities}
                  members={members}
                  currentUserId={currentUserId}
                  currentMemberName={currentMemberName}
                  activeRole={activeRole}
                  dataMode={dataMode}
                  teamId={team.id}
                  teamOwnerId={team.ownerId}
                  onSaveAvailability={handleSaveAvailability}
                  onDeleteAvailability={handleDeleteAvailability}
                  onCreatePlannedScrimFromWindow={async (draft) => {
                    const scrim: Scrim = {
                      id: createClientId('scrim'),
                      teamId: team.id,
                      teamOwnerId: team.ownerId,
                      createdBy: currentUserId,
                      opponent: draft.opponent,
                      date: draft.date,
                      startTime: draft.startTime,
                      endTime: draft.endTime,
                      mapCount: 2,
                      maps: ['Ascent', 'Lotus'],
                      server: 'Singapore',
                      status: 'planned',
                      notes: 'Đề xuất từ khung giờ rảnh chung của đội (chờ xác nhận).',
                    };
                    await handleSaveScrim(scrim, true);
                    setActiveSection('scrim-schedule');
                  }}
                />
              )}

              {activeSection === 'team-management' && (
                <TeamManagementView
                  team={team}
                  members={members}
                  drills={drills}
                  availabilities={availabilities}
                  activeRole={activeRole}
                  currentUserId={currentUserId}
                  dataMode={dataMode}
                  onSwitchPreviewRole={
                    dataMode === 'demo' ? setDemoRolePreview : undefined
                  }
                  onSaveMember={handleSaveMember}
                  onDeleteMember={handleDeleteMember}
                  onAssignDrill={handleAssignDrill}
                  onNavigate={setActiveSection}
                />
              )}

              {activeSection === 'performance' && (
                <PerformanceView
                  drills={drills}
                  aimLogs={aimLogs}
                  scrims={scrims}
                />
              )}
            </>
          )}
        </main>
      </div>

      <NotificationDrawer
        open={notificationsOpen}
        onClose={() => setNotificationsOpen(false)}
        notifications={notifications}
        onMarkRead={handleMarkNotifRead}
        onMarkAllRead={handleMarkAllNotifsRead}
      />

      <AuthModal
        open={authModalOpen}
        busy={authBusy}
        error={authError}
        savedAccounts={listLocalAccountIdentifiers()}
        onClose={() => setAuthModalOpen(false)}
        onClearError={() => setAuthError('')}
        onSubmit={handleAuthSubmit}
      />
    </div>
  );
}

export default function App() {
  return (
    <ErrorBoundary>
      <AppShell />
    </ErrorBoundary>
  );
}
