export function loadDemoState(): HubDataset {
  try {
    const raw = localStorage.getItem(DEMO_STORAGE_KEY);
    if (raw) {
      const parsed = JSON.parse(raw) as HubDataset;
      if (parsed && parsed.team && Array.isArray(parsed.drills)) {
        return parsed;
      }
    }
  } catch {
    // ignore corrupted localStorage and fall back to fresh seed
  }
  const fresh = buildDemoDataset();
  saveDemoState(fresh);
  return fresh;
}

export function saveDemoState(data: HubDataset): void {
  try {
    localStorage.setItem(DEMO_STORAGE_KEY, JSON.stringify(data));
  } catch {
    // ignore storage quota errors
  }
}

export function resetDemoState(): HubDataset {
  const fresh = buildDemoDataset();
  saveDemoState(fresh);
  return fresh;
}
