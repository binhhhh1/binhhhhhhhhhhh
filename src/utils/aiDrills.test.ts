function createMemoryStorage(): Storage {
  const store = new Map<string, string>();
  return {
    get length() {
      return store.size;
    },
    clear() {
      store.clear();
    },
    getItem(key: string) {
      return store.has(key) ? store.get(key)! : null;
    },
    key(index: number) {
      return Array.from(store.keys())[index] ?? null;
    },
    removeItem(key: string) {
      store.delete(key);
    },
    setItem(key: string, value: string) {
      store.set(key, String(value));
    },
  };
}

test('normalizeGeneratedDrills sanitizes AI output and enforces valid categories & bounds', () => {
  const drills = normalizeGeneratedDrills(
    [
      {
        title: 'VT Smoothbot Tracking',
        category: 'Aim Training',
        focusTag: 'Tracking',
        startTime: '09:30',
        durationMin: 25,
        goal: '>= 85% tracking accuracy',
        description: 'Theo sát mục tiêu di chuyển ngang liên tục.',
      },
      {
        title: 'Static 1w4ts Flicks',
        category: 'InvalidCategory',
        focusTag: 'Crosshair Placement',
        startTime: '99:99',
        durationMin: 999,
        goal: '105k score',
      },
      {
        title: '',
      },
    ],
    '2026-11-17',
  );

  assert.equal(drills.length, 2);
  assert.equal(drills[0].id, 'ai_2026-11-17_1');
  assert.equal(drills[0].category, 'Aim Training');
  assert.equal(drills[1].category, 'Crosshair Placement');
  assert.equal(drills[1].startTime, '09:45');
  assert.equal(drills[1].durationMin, 180);

  const converted = toTrainingDrill(drills[0], {
    id: 'drill_1',
    date: '2026-11-17',
    teamId: 'team_1',
    teamOwnerId: 'u1',
    ownerId: 'u1',
    assignedBy: 'u1',
  });
  assert.equal(converted.status, 'todo');
  assert.match(converted.description || '', /\[AI · Tracking\]/);
});

test('daily AI cache key & auto-generation rule triggers once per VN date per account', () => {
  const key = buildDailyAiCacheKey('acct_123', '2026-11-17');
  assert.equal(key, 'vth_ai_daily_acct_123_2026-11-17');
  assert.equal(shouldAutoGenerateDailyPlan(null, '2026-11-17'), true);
  assert.equal(shouldAutoGenerateDailyPlan('2026-11-16', '2026-11-17'), true);
  assert.equal(shouldAutoGenerateDailyPlan('2026-11-17', '2026-11-17'), false);
});

test('localAuth registers, logs in, rejects bad password, and isolates account workspaces', async () => {
  const storage = createMemoryStorage();

  const regA = await registerLocalAccount(
    {
      identifier: 'KyroVN',
      password: 'secret123',
      displayName: 'Minh Kyro',
      riotId: 'Kyro#VN1',
      teamRole: 'player',
      gameRole: 'Duelist',
      mainAgent: 'Jett',
    },
    storage,
  );
  assert.equal(regA.session.profile.riotId, 'Kyro#VN1');
  assert.equal(regA.dataset.drills.length, 0);

  // Add drill to Account A workspace
  saveAccountWorkspace(
    regA.session.account.uid,
    {
      ...regA.dataset,
      drills: [
        {
          id: 'd_a1',
          teamId: regA.dataset.team.id,
          teamOwnerId: regA.session.account.uid,
          ownerId: regA.session.account.uid,
          assignedBy: regA.session.account.uid,
          title: 'Account A Flick Drill',
          category: 'Aim Training',
          date: '2026-11-17',
          startTime: '10:00',
          durationMin: 30,
          status: 'todo',
        },
      ],
    },
    storage,
  );

  // Duplicate identifier rejected (case-insensitive)
  await assert.rejects(
    () =>
      registerLocalAccount(
        {
          identifier: 'kyrovn',
          password: 'password99',
          displayName: 'Dup',
          riotId: 'Dup#1',
          teamRole: 'player',
          gameRole: 'Flex',
          mainAgent: 'Omen',
        },
        storage,
      ),
    /tồn tại/,
  );

  // Account B starts isolated
  const regB = await registerLocalAccount(
    {
      identifier: 'zen@team.vn',
      password: 'zenpass123',
      displayName: 'Zen',
      riotId: 'Zen#VN2',
      teamRole: 'coach',
      gameRole: 'Initiator',
      mainAgent: 'Sova',
    },
    storage,
  );
  assert.equal(regB.dataset.drills.length, 0);

  // Wrong password rejected
  await assert.rejects(
    () => loginLocalAccount('kyrovn', 'wrongpass', storage),
    /Mật khẩu/,
  );

  // Log back into Account A -> sees Account A drill
  logoutLocalAccount(storage);
  assert.equal(getActiveLocalSession(storage), null);

  const loginA = await loginLocalAccount('kyrovn', 'secret123', storage);
  assert.equal(loginA.dataset.drills.length, 1);
  assert.equal(loginA.dataset.drills[0].title, 'Account A Flick Drill');
  assert.equal(getActiveLocalSession(storage)?.session.account.uid, regA.session.account.uid);
});
